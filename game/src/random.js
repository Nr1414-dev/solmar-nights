// SOLMAR NIGHTS — random.js
// A small seeded generator (mulberry32) so the city, the traffic and the
// screenshot scenes are the same every run for the same seed. Gameplay
// randomness goes through the world's own rng too, so a ?shot= scene can be
// replayed exactly.

export function createRandom(seed) {
  let a = seed >>> 0;
  return {
    next() {
      a |= 0;
      a = (a + 0x6d2b79f5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    },
    range(min, max) {
      return min + this.next() * (max - min);
    },
    int(min, max) {
      return Math.floor(this.range(min, max + 1));
    },
    pick(list) {
      return list[Math.floor(this.next() * list.length)];
    },
    chance(p) {
      return this.next() < p;
    },
    /** A shuffled copy (Fisher-Yates), so callers can deal a random order without mutating the source list. */
    shuffle(list) {
      const out = list.slice();
      for (let i = out.length - 1; i > 0; i--) {
        const j = Math.floor(this.next() * (i + 1));
        [out[i], out[j]] = [out[j], out[i]];
      }
      return out;
    },
    /** Pick a value from [value, weight] pairs, weighted by the second element. */
    weightedPick(pairs) {
      let total = 0;
      for (const [, w] of pairs) total += w;
      let roll = this.next() * total;
      for (const [v, w] of pairs) {
        roll -= w;
        if (roll <= 0) return v;
      }
      return pairs[pairs.length - 1][0];
    },
  };
}

export const clamp = (v, min, max) => (v < min ? min : v > max ? max : v);
export const lerp = (a, b, t) => a + (b - a) * t;
export const dist = (x1, y1, x2, y2) => Math.hypot(x2 - x1, y2 - y1);
export const angleTo = (x1, y1, x2, y2) => Math.atan2(y2 - y1, x2 - x1);
export const angleDiff = (a, b) => {
  let d = (b - a) % (Math.PI * 2);
  if (d > Math.PI) d -= Math.PI * 2;
  if (d < -Math.PI) d += Math.PI * 2;
  return d;
};
